	<p>Dipolis steht unter GPL-3. Die ursprünglichen Lizenzdateien und Herkunftsangaben bleiben erhalten.</p>
	<h2>Änderungen gegenüber dem Original</h2>
	<ul>
		<li>Menschen und KI-Bewohner mit getrennten Wohnzonen, Versorgung und Strombedarf.</li>
		<li>Nahrung, Farmen, Grundversorgung, Arbeitslosigkeit und Automatisierung mit zusätzlichen Einnahmen.</li>
		<li>Regelprofile für Unruhe, Proteste, Sabotage und Aufstände.</li>
		<li>Anlagen, Einweisungen und KI-Fraktionen in erweiterten Regelprofilen.</li>
		<li>Eine Dipolis-Oberfläche mit Live-Modus, reproduzierbarer Wiedergabe und eigenen Werkzeugen.</li>
		<li>Modellgeführte Verwaltung, protokollierte Entscheidungen, Kennzahlenberichte und unabhängige Nachbetrachtungen.</li>
		<li>Korrekturen an Speicherzugriffen und reproduzierbaren Engine-Läufen.</li>
	</ul>
	<p>Die Arbeit von Will Wright, Don Hopkins, Electronic Arts und den ursprünglichen Mitwirkenden bildet die Grundlage. Dipolis ist kein Produkt von Electronic Arts.</p>
