	<h1>Über Dipolis</h1>
	<p>Dipolis ist eine veränderte Fassung von Micropolis, beruhend auf dem 2008 von Electronic Arts unter GPL-3 veröffentlichten Quellcode und der Engine-Portierung MicropolisCore von Don Hopkins.</p>
	<p>Ursprung: <a href="https://github.com/SimHacker/MicropolisCore">MicropolisCore</a>.
		Ausgangs-Commit:
		<a href="https://github.com/SimHacker/MicropolisCore/commit/f9ae6a57bbe5f5ff94c149bccb3015757f18241d">f9ae6a57bbe5f5ff94c149bccb3015757f18241d</a>.
	</p>
